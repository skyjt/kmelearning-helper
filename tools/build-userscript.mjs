import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = path.join(projectRoot, "userscript", "kme-learning-helper.user.js");
const checkOnly = process.argv.includes("--check");

const [manifestText, source, styles, iconSvg] = await Promise.all([
  fs.readFile(path.join(projectRoot, "manifest.json"), "utf8"),
  fs.readFile(path.join(projectRoot, "content.js"), "utf8"),
  fs.readFile(path.join(projectRoot, "styles.css"), "utf8"),
  fs.readFile(path.join(projectRoot, "icons", "icon.svg"), "utf8")
]);

const manifest = JSON.parse(manifestText);
const iconDataUrl = `data:image/svg+xml;base64,${Buffer.from(iconSvg).toString("base64")}`;
const metadata = `// ==UserScript==
// @name         KME 学习助手
// @namespace    https://github.com/skyjt/kmelearning-helper
// @version      ${manifest.version}
// @description  自动按目录学习 KME 课程，并等待平台确认完成后继续下一门。
// @author       skyjt
// @license      MIT
// @homepageURL  https://github.com/skyjt/kmelearning-helper
// @supportURL   https://github.com/skyjt/kmelearning-helper/issues
// @updateURL    https://raw.githubusercontent.com/skyjt/kmelearning-helper/main/userscript/kme-learning-helper.user.js
// @downloadURL  https://raw.githubusercontent.com/skyjt/kmelearning-helper/main/userscript/kme-learning-helper.user.js
// @match        https://pc.kmelearning.com/*
// @icon         ${iconDataUrl}
// @run-at       document-idle
// @noframes
// @grant        GM_getValue
// @grant        GM_setValue
// @grant        GM_addStyle
// ==/UserScript==`;

const generated = `${metadata}

// Generated by tools/build-userscript.mjs from content.js, styles.css and icons/icon.svg.
// Edit the shared source files, then run npm run build:userscript.
(() => {
  "use strict";

  const USERSCRIPT_ICON_URL = ${JSON.stringify(iconDataUrl)};
  const USERSCRIPT_STYLES = ${JSON.stringify(styles)};

  // Keep the shared content script unchanged by presenting the small callback-style subset
  // of the Chrome APIs it uses. Tampermonkey owns the underlying persistent storage.
  const userscriptStorage = {
    get(defaults, callback) {
      const values = {};
      for (const [key, fallback] of Object.entries(defaults || {})) {
        try {
          values[key] = GM_getValue(key, fallback);
        } catch {
          values[key] = fallback;
        }
      }
      callback?.(values);
    },
    set(patch, callback) {
      for (const [key, value] of Object.entries(patch || {})) {
        try {
          GM_setValue(key, value);
        } catch {
          // A failed preference write must not stop the page-side learning state machine.
        }
      }
      callback?.();
    }
  };

  const chrome = {
    storage: { local: userscriptStorage },
    runtime: {
      getURL() {
        return USERSCRIPT_ICON_URL;
      }
    }
  };

  if (typeof GM_addStyle === "function") {
    GM_addStyle(USERSCRIPT_STYLES);
  } else {
    const style = document.createElement("style");
    style.textContent = USERSCRIPT_STYLES;
    document.documentElement.appendChild(style);
  }

${source.trimEnd()}
})();
`;

if (checkOnly) {
  let current = "";
  try {
    current = await fs.readFile(outputPath, "utf8");
  } catch {
    // A missing generated file is reported by the same stale-output error below.
  }
  if (current !== generated) {
    throw new Error("油猴脚本尚未生成或已经过期，请运行 npm run build:userscript");
  }
  console.log(`油猴脚本已是最新版本：${path.relative(projectRoot, outputPath)}`);
} else {
  await fs.mkdir(path.dirname(outputPath), { recursive: true });
  await fs.writeFile(outputPath, generated);
  console.log(`已生成 ${path.relative(projectRoot, outputPath)} (${manifest.version})`);
}
